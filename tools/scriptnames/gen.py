#!/usr/bin/env python3
"""Builds the loader's script name table (src/loader/src/script_names.tsv) from RuneLite's decompiled client scripts.

The cache stores no script names (every script blob starts with an empty name), so the names are the ones the community
gave the decompiled scripts. https://github.com/runelite/cs2-scripts has a file per script, named `[clientscript,name].cs2`
or `[proc,name].cs2`, whose first line is `// <script id>` (or, for one the decompiler failed on, an error that names it). Scripts it could not name (`script4730`) are left out.

    git clone --depth 1 https://github.com/runelite/cs2-scripts /tmp/cs2-scripts
    python3 -I tools/scriptnames/gen.py /tmp/cs2-scripts > src/loader/src/script_names.tsv

Script ids are the cache's, so the table is right for the build the repository was decompiled from; a name that has
moved shows against the wrong script, which is why the table says which commit it is from.
"""
import re
import subprocess
import sys
from pathlib import Path

FILE = re.compile(r"^\[(clientscript|proc),([^\]]+)\]\.cs2$")
UNNAMED = re.compile(r"^script\d+$")


def read_names(scripts: Path):
    """(id, name) for every script with a name; a script with two names or a name read twice is an error."""
    found = {}
    for path in sorted(scripts.iterdir()):
        match = FILE.match(path.name)
        if not match or UNNAMED.match(match.group(2)):
            continue
        with path.open(encoding="utf-8", errors="replace") as file:
            first = file.readline().strip()
        # a script RuneLite's decompiler failed on has the error there instead, which names the script
        id_match = re.fullmatch(r"// (\d+)", first) or re.search(r"in script (\d+)", first)
        if not id_match:
            print(f"skipped {path.name}: no script id in {first!r}", file=sys.stderr)
            continue
        script_id = int(id_match.group(1))
        if script_id in found:
            raise SystemExit(f"script {script_id} is named twice: {found[script_id]} and {match.group(2)}")
        found[script_id] = match.group(2)
    return sorted(found.items())


def commit(repo: Path) -> str:
    try:
        out = subprocess.run(["git", "-C", str(repo), "log", "-1", "--format=%cs %h"], capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    repo = Path(sys.argv[1])
    names = read_names(repo / "scripts")
    print("# Names of the client's scripts: id, name. The cache has none; these are RuneLite's names for the decompiled scripts.")
    print("# Generated by tools/scriptnames/gen.py from https://github.com/runelite/cs2-scripts; do not edit.")
    print(f"# {len(names)} named")
    print(f"# source\t{commit(repo)}")
    for script_id, name in names:
        print(script_id, name, sep="\t")


if __name__ == "__main__":
    main()
